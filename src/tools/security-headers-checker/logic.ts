/** A ready-made `curl -I` command the user can paste into a terminal. */
export function curlCommand(url: string): string {
  const trimmed = url.trim()
  return `curl -sSI ${trimmed === '' ? 'https://example.com' : trimmed}`
}

const STATUS_LABEL: Record<HeaderFinding['status'], string> = {
  pass: 'OK',
  warn: 'Improve',
  fail: 'Fix',
  absent: 'Missing',
  info: 'Note',
}

/** The order findings are listed in: problems first, then passes. */
const STATUS_RANK: Record<HeaderFinding['status'], number> = {
  fail: 0,
  absent: 1,
  warn: 2,
  pass: 3,
  info: 4,
}

/** Sort findings so the ones that need attention appear first. */
export function sortFindings(findings: HeaderFinding[]): HeaderFinding[] {
  return [...findings].sort((a, b) => {
    const rank = STATUS_RANK[a.status] - STATUS_RANK[b.status]
    if (rank !== 0) return rank
    return b.weight - a.weight
  })
}

/** How many findings of each status, for the summary strip. */
export function countByStatus(findings: HeaderFinding[]): Record<HeaderFinding['status'], number> {
  const counts: Record<HeaderFinding['status'], number> = {
    pass: 0,
    warn: 0,
    fail: 0,
    absent: 0,
    info: 0,
  }
  for (const finding of findings) counts[finding.status] += 1
  return counts
}

/**
 * Build a Markdown report the user can save or paste into a ticket.
 *
 * `source` is shown in the heading so a pasted report is never mistaken for a
 * live probe.
 */
export function buildMarkdownReport(
  findings: HeaderFinding[],
  options: { source: string; score: number },
): string {
  const grade = gradeSecurityScore(options.score)
  const counts = countByStatus(findings)
  const lines: string[] = [
    '# Security headers report',
    '',
    `- Source: ${options.source}`,
    `- Score: ${options.score}/100 (${grade.label})`,
    `- Passed: ${counts.pass}, improve: ${counts.warn}, missing or failing: ${counts.fail + counts.absent}`,
    `- Generated: ${new Date().toISOString()}`,
    '',
    '## Findings',
    '',
  ]

  for (const finding of sortFindings(findings)) {
    lines.push(`### ${finding.name} — ${STATUS_LABEL[finding.status]}`)
    lines.push('')
    lines.push(`- Protects against: ${finding.protects}`)
    lines.push(`- Value: ${finding.value === null ? '(not sent)' : `\`${finding.value}\``}`)
    lines.push(`- Note: ${finding.note}`)
    lines.push('')
  }

  lines.push('---')
  lines.push('')
  lines.push(
    'Generated by TOOLZEN. Header analysis is a starting point, not a security audit — configuration inside the application matters just as much.',
  )
  lines.push('')

  return lines.join('\n')
}

/** Human label for a finding status. */
export function statusLabel(status: HeaderFinding['status']): string {
  return STATUS_LABEL[status]
}
